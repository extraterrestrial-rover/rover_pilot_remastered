#!/usr/bin/env python3
"""Generate the arm protocol test vectors from the Python reference implementation.

Writes the same vectors for both test suites, so the C++ arm firmware and the Python arm driver are checked against
each other byte for byte (serial packets and I2C frames):
  firmware_arm/test/test_native/vectors.h
  ros2_ws/src/arm_pilot_redemption/test/vectors.json

    python3 tools/arm_gen_test_vectors.py          # regenerate
    python3 tools/arm_gen_test_vectors.py --check  # exit 1 if either file is out of date
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'ros2_ws' / 'src' / 'arm_pilot_redemption'))

from arm_pilot_redemption import protocol  # noqa: E402

HEADER = ROOT / 'firmware_arm' / 'test' / 'test_native' / 'vectors.h'
JSON = ROOT / 'ros2_ws' / 'src' / 'arm_pilot_redemption' / 'test' / 'vectors.json'

COMMANDS = [
    # name, seq, estop, targets shoulder elbow wrist_a wrist_b (rpm)
    ('neutral', 0, False, (0.0, 0.0, 0.0, 0.0)),
    ('shoulder_full', 1, False, (117.0, 0.0, 0.0, 0.0)),
    ('wrist_roll', 2, False, (-20.5, 3.3, 60.0, -60.0)),
    ('estop', 255, True, (0.0, 0.0, 0.0, 0.0)),
]
STATUS = protocol.ArmStatus(
    state=protocol.FAULT, flags=0, command_age_ms=20, rx_good=1234, rx_bad=2, uptime_ms=600000, reset_reason=1,
    firmware_version=(1, 0, 0), motors=(
        protocol.MotorStatus(protocol.ENABLED, 0, 0, 128, 58.5, 100000, 0),
        protocol.MotorStatus(protocol.ENABLED, 0, 0, -255, -117.0, -5, 3),
        protocol.MotorStatus(protocol.FAULT, protocol.SLAVE_FAULT_STALL, protocol.LINK_SLAVE_FAULT, 0, 0.0, -2000000, 0),
        protocol.MotorStatus(protocol.BOOT, 0, protocol.LINK_LOST, 0, 0.0, 0, 65535)))
INFO = (protocol.MotorInfo(117.0, 1425.1, (1, 0, 0), 1), protocol.MotorInfo(117.0, 1425.1, (1, 0, 0), 1),
        protocol.MotorInfo(312.0, 537.7, (1, 0, 0), 3), protocol.MotorInfo(0.0, 0.0, (0, 0, 0), 0))
SLAVE_COMMANDS = [
    ('neutral', protocol.SlaveCommand(0, False, 0.0)),
    ('reverse', protocol.SlaveCommand(77, False, -58.5)),
    ('estop', protocol.SlaveCommand(255, True, 0.0)),
]
SLAVE_STATUS = protocol.SlaveStatus(counter=42, state=protocol.ENABLED, faults=0, joint=2, pwm=-128, velocity_rpm=-58.5,
                                    position=-123456, rx_bad=7, command_age_ms=15, max_rpm=117.0, counts_per_rev=1425.1,
                                    firmware_version=(1, 0, 0), reset_reason=1)


def build() -> dict:
    commands = []
    for name, seq, estop, targets in COMMANDS:
        payload = protocol.arm_command_payload(estop, targets)
        commands.append({'name': name, 'seq': seq, 'estop': estop, 'targets_rpm': list(targets), 'payload': payload.hex(),
                         'wire': protocol.encode_packet(protocol.TYPE_ARM_COMMAND, seq, payload).hex()})
    status_payload = protocol.arm_status_payload(STATUS)
    info_payload = protocol.arm_info_payload(INFO)
    return {
        'crc_check': {'input': '123456789', 'crc': protocol.crc16(b'123456789')},
        'commands': commands,
        'status': {'seq': 7, 'payload': status_payload.hex(),
                   'wire': protocol.encode_packet(protocol.TYPE_ARM_STATUS, 7, status_payload).hex()},
        'info': {'seq': 8, 'payload': info_payload.hex(),
                 'wire': protocol.encode_packet(protocol.TYPE_ARM_INFO, 8, info_payload).hex()},
        'slave_commands': [{'name': name, 'seq': command.seq, 'estop': command.estop, 'target_rpm': command.target_rpm,
                            'frame': protocol.slave_command_frame(command).hex()} for name, command in SLAVE_COMMANDS],
        'slave_status': {'frame': protocol.slave_status_frame(SLAVE_STATUS).hex()},
    }


def c_bytes(hex_text: str) -> str:
    return ', '.join(f'0x{hex_text[i:i + 2]}' for i in range(0, len(hex_text), 2))


def render_header(vectors: dict) -> str:
    lines = ['// Generated by tools/arm_gen_test_vectors.py from the Python reference protocol. Do not edit.',
             '#pragma once', '#include <stddef.h>', '#include <stdint.h>', '',
             f"static const uint16_t kCrcCheck = 0x{vectors['crc_check']['crc']:04X};  // crc16(\"123456789\")", '',
             'struct CommandVector { const char* name; uint8_t seq; bool estop; float targets[4]; const uint8_t* wire; size_t wire_len; };',
             'struct SlaveCommandVector { const char* name; uint8_t seq; bool estop; float target; const uint8_t* frame; };', '']
    for command in vectors['commands']:
        lines.append(f"static const uint8_t kWire_{command['name']}[] = {{{c_bytes(command['wire'])}}};")
    lines += ['', 'static const CommandVector kCommandVectors[] = {']
    for command in vectors['commands']:
        targets = ', '.join(f'{value:.1f}f' for value in command['targets_rpm'])
        lines.append(f"    {{\"{command['name']}\", {command['seq']}, {str(command['estop']).lower()}, {{{targets}}}, "
                     f"kWire_{command['name']}, sizeof(kWire_{command['name']})}},")
    lines += ['};', '']
    for command in vectors['slave_commands']:
        lines.append(f"static const uint8_t kSlaveFrame_{command['name']}[] = {{{c_bytes(command['frame'])}}};")
    lines += ['', 'static const SlaveCommandVector kSlaveCommandVectors[] = {']
    for command in vectors['slave_commands']:
        lines.append(f"    {{\"{command['name']}\", {command['seq']}, {str(command['estop']).lower()}, {command['target_rpm']:.1f}f, "
                     f"kSlaveFrame_{command['name']}}},")
    lines += ['};', '',
              f"static const uint8_t kStatusSeq = {vectors['status']['seq']};",
              f"static const uint8_t kStatusWire[] = {{{c_bytes(vectors['status']['wire'])}}};",
              f"static const uint8_t kInfoSeq = {vectors['info']['seq']};",
              f"static const uint8_t kInfoWire[] = {{{c_bytes(vectors['info']['wire'])}}};",
              f"static const uint8_t kSlaveStatusFrame[] = {{{c_bytes(vectors['slave_status']['frame'])}}};", '']
    return '\n'.join(lines)


def main() -> int:
    vectors = build()
    outputs = {HEADER: render_header(vectors), JSON: json.dumps(vectors, indent=2) + '\n'}
    if '--check' in sys.argv:
        stale = [path for path, text in outputs.items() if not path.exists() or path.read_text() != text]
        for path in stale:
            print(f'{path.relative_to(ROOT)} is out of date; run tools/arm_gen_test_vectors.py', file=sys.stderr)
        return 1 if stale else 0
    for path, text in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    return 0


if __name__ == '__main__':
    sys.exit(main())
